/**
 * Credits and licences: the libraries, data and models the app is made with, each with its
 * licence (the list AboutLibraries gathers at build time, with app/aboutlibraries' entries), then
 * the third-party notices of the native libraries it ships (assets/licences, from
 * tools/fetch_notices.py), each read in full on a tap.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun CreditsScreen(onBack: () -> Unit) {
    val context = LocalContext.current
    // The notice being read (its file in assets/licences), or null for the list.
    var notice by rememberSaveable { mutableStateOf<String?>(null) }
    val back = { if (notice != null) notice = null else onBack() }
    BackHandler(onBack = back)
    val generated by produceLibraries(R.raw.aboutlibraries)
    val libraries = remember(generated) { generated?.let(::creditsList) }
    // Kept while a notice is read, so back returns to where the list was (the notices are at its end).
    val listState = rememberLazyListState()
    val notices = remember { context.assets.list(NOTICES).orEmpty().sorted() }
    // The library whose licence is shown, in the app: its text carries the copyright lines a
    // licence's web page does not, and needs no connection.
    var licenceOf by remember { mutableStateOf<Library?>(null) }
    Scaffold(topBar = {
        TopAppBar(
            title = { Text(notice?.let { noticeTitle(it) ?: it } ?: "Credits and licences") },
            navigationIcon = { IconButton(onClick = back) { Icon(Icons.AutoMirrored.Outlined.ArrowBack, "Back") } },
        )
    }) { padding ->
        val open = notice
        if (open != null) {
            NoticeText(open, Modifier.fillMaxSize().padding(padding))
        } else {
            LibrariesContainer(
                libraries,
                dialogLibrary = licenceOf,
                sheetLibrary = null,
                onDialogLibraryChange = { licenceOf = it },
                onSheetLibraryChange = {},
                modifier = Modifier.fillMaxSize().padding(padding),
                lazyListState = listState,
                onActionClick = { library, kind ->
                    val text = kind == LibraryActionKind.License && library.licenses.any { !it.licenseContent.isNullOrBlank() }
                    if (text) licenceOf = library
                    text
                },
                header = {
                    item {
                        Text(
                            "NLSGallery ${BuildConfig.VERSION_NAME} is made with these: the place names and AI models " +
                                "first, then the code reproduced from other projects, then the libraries. Tap one for its " +
                                "licence. The notices of the code inside the native libraries are at the end.",
                            style = MaterialTheme.typography.bodyMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            modifier = Modifier.padding(16.dp),
                        )
                    }
                },
                footer = {
                    item { HorizontalDivider(Modifier.padding(top = 8.dp)) }
                    items(notices) { file ->
                        Column(Modifier.fillMaxWidth().clickable { notice = file }.padding(horizontal = 20.dp, vertical = 12.dp)) {
                            Text(noticeTitle(file) ?: file, style = MaterialTheme.typography.titleMedium)
                            Text(
                                "The licences of the open-source code built into it",
                                style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                            )
                        }
                    }
                },
            )
        }
    }
}

/** The notices folder in assets. */
private const val NOTICES = "licences"

/**
 * [libs] as the screen lists them: the data and models first, then the code reproduced from other
 * projects (app/aboutlibraries' entries, by their tags), then the libraries, each part by name as
 * generated; and of each library's licences, those with its text when it has one. An entry in
 * app/aboutlibraries adds a library's real licence to the one its POM names (the plugin merges,
 * it does not replace), and that one may be a bare template ("Copyright (c) <year> <copyright
 * holders>") or have no text.
 */
internal fun creditsList(libs: Libs): Libs = libs.copy(
    libraries = libs.libraries.sortedBy { TAG_ORDER[it.tag] ?: TAG_ORDER.size }.map { library ->
        val real = library.licenses.filter { isRealText(it.licenseContent) }
        if (real.isEmpty() || real.size == library.licenses.size) library else library.copy(licenses = real.toSet())
    },
)

/** Whether [text] is a licence's own text: not missing, not a template waiting for its holder. */
internal fun isRealText(text: String?): Boolean = !text.isNullOrBlank() && TEMPLATE_HOLES.none { it in text }

/** What SPDX's MIT and BSD templates have where a copyright line goes. */
private val TEMPLATE_HOLES = listOf("<copyright holders>", "<year>", "<owner>", "<YEAR>", "<OWNER>")

/** Where app/aboutlibraries' entries go, by their tags. */
private val TAG_ORDER = mapOf("data" to 0, "model" to 0, "port" to 1)

/** The native libraries whose notices tools/fetch_notices.py fetches, by their files' prefixes. */
private val NOTICE_NAMES = mapOf(
    "onnxruntime-qnn" to "ONNX Runtime's QNN execution provider",
    "onnxruntime" to "ONNX Runtime",
    "qnn-runtime" to "Qualcomm QNN runtime",
)

/**
 * How notice [file] reads in the list ("onnxruntime-1.31.1-ThirdPartyNotices.txt": "ONNX Runtime
 * 1.31.1: notices"), or null for a file not one of [NOTICE_NAMES].
 */
internal fun noticeTitle(file: String): String? {
    val m = Regex("^([a-z-]+?)-(\\d[^-]*)-[A-Za-z]+\\.txt$").find(file) ?: return null
    val name = NOTICE_NAMES[m.groupValues[1]] ?: return null
    return "$name ${m.groupValues[2]}: notices"
}

/**
 * [paragraph] with the line breaks a text file wraps at (about 80 columns) taken out, so it wraps
 * to the screen: a line of words that long runs on into the next, unless that one starts a list
 * item. Short lines (an address, a heading) and rules ("=====") keep their breaks, and so does a
 * paragraph with a line longer than any a file wraps at: its lines are paragraphs of their own
 * (Qualcomm's notice opens so).
 */
internal fun reflow(paragraph: String): String {
    if (paragraph.lines().any { it.trimEnd().length > UNWRAPPED }) return paragraph
    val out = StringBuilder()
    var previous = ""
    for (line in paragraph.lines()) {
        if (out.isNotEmpty()) {
            val runsOn = previous.trimEnd().length >= WRAPPED && WORDS.containsMatchIn(previous) &&
                WORDS.containsMatchIn(line) && !LIST_ITEM.containsMatchIn(line)
            out.append(if (runsOn) " " else "\n")
        }
        out.append(if (out.isEmpty() || out.endsWith("\n")) line.trimEnd() else line.trim())
        previous = line
    }
    return out.toString()
}

/** A line at least this long was wrapped by the file, not ended by its author. */
private const val WRAPPED = 60

/** A line longer than this was not wrapped by the file at all. */
private const val UNWRAPPED = 100

/** Something a line of text has and a rule ("=====", "-----") has not. */
private val WORDS = Regex("[\\p{L}\\p{N}]")

/** A line starting a list item: "* ", "- ", "1. ", "(a) ". */
private val LIST_ITEM = Regex("^\\s*([*\\-•]\\s|\\d+[.)]\\s|\\([a-z0-9]+\\)\\s)")

/** Notice [file], in paragraphs: a few hundred KB, too much for one text. */
@Composable
private fun NoticeText(file: String, modifier: Modifier) {
    val context = LocalContext.current
    val paragraphs by produceState(emptyList<String>(), file) {
        value = withContext(Dispatchers.IO) {
            context.assets.open("$NOTICES/$file").use { it.readBytes().toString(Charsets.UTF_8) }
                .split(Regex("\n[ \t]*\n")).map { reflow(it.trim('\n')) }.filter { it.isNotBlank() }
        }
    }
    LazyColumn(modifier.padding(horizontal = 16.dp)) {
        items(paragraphs) { p ->
            Text(p, style = MaterialTheme.typography.bodySmall, modifier = Modifier.padding(vertical = 4.dp))
        }
    }
}
